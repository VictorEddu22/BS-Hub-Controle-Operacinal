require('dotenv').config();
const express=require('express');
const cors=require('cors');
const app=express();
app.disable('x-powered-by');
app.use(cors({origin:process.env.FRONTEND_URL||'http://localhost:5173'}));
app.use(express.json({limit:'3mb'}));
app.get('/health',(req,res)=>res.json({ok:true,database:'mysql'}));
app.use('/public',require('./routes/publicRoutes'));
app.use('/auth',require('./routes/authRoutes'));
app.use('/profile',require('./routes/profileRoutes'));
app.use('/services',require('./routes/servicesRoutes'));
app.use('/barbers',require('./routes/barbersRoutes'));
app.use('/hours',require('./routes/hoursRoutes'));
app.use('/appointments',require('./routes/appointmentsRoutes'));
app.use('/clients',require('./routes/clientsRoutes'));
app.use('/settings',require('./routes/settingsRoutes'));
app.use('/notifications',require('./routes/notificationsRoutes'));
app.use('/reports',require('./routes/reportsRoutes'));
app.use('/dashboard',require('./routes/dashboardRoutes'));
app.use((req,res)=>res.status(404).json({mensagem:'Rota não encontrada.'}));
app.use((err,req,res,next)=>{console.error(err);res.status(500).json({mensagem:'Erro interno do servidor.'});});
const port=Number(process.env.PORT||3000);
app.listen(port,()=>console.log(`BSHub API em http://localhost:${port} | MySQL`));
